import assert from "node:assert/strict";
import { load } from "./headless.mjs";
const { Player } = await load("js/player.js");
const { TREES, loadSkillPoints } = await load("js/skills.js");
const p = new Player(0, 0, { id: "novice" });
const skill = TREES.novice.find(s => !s.req);
assert.equal(p.skillPoints, 0);
assert.equal(p.pathPoints, 0);
p.addExp(p.expNext);
assert.equal(p.skillPoints, 1);
assert.equal(p.pathPoints, 1);
assert.equal(p.learnSkill("brawn"), true);
assert.equal(p.skillPoints, 1);
assert.equal(p.pathPoints, 0);
assert.equal(p.learnSkill("nimble"), false);
assert.equal(p.learnSkill(skill.id), true);
assert.equal(p.skillPoints, 0);
p.resetSkills("skills");
assert.equal(p.skillPoints, 1);
assert.equal(p.pathPoints, 0);
assert.equal(p.skillLevels.brawn, 1);
p.resetSkills("paths");
assert.equal(p.pathPoints, 1);
assert.equal(p.skillPoints, 1);
p.skillLevels = { brawn: 2, [skill.id]: 1 };
p.level = 5;
loadSkillPoints(p, { skillPoints: 1 });
assert.equal(p.skillPoints, 3);
assert.equal(p.pathPoints, 2);
loadSkillPoints(p, { skillPoints: 7, pathPoints: 4 });
assert.equal(p.skillPoints, 7);
assert.equal(p.pathPoints, 4);
p.resetSkills();
assert.equal(p.skillPoints, 8);
assert.equal(p.pathPoints, 6);
assert.deepEqual(p.skillLevels, {});
console.log("Independent skill/path spending, level-up, refunds, and save migration passed.");
