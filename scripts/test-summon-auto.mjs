import assert from "node:assert/strict";
import { load } from "./headless.mjs";
const { Player } = await load("js/player.js");
const { LootManager } = await load("js/loot.js");
const { Familiar } = await load("js/summons/familiar.js");
const { FalconCompanion } = await load("js/summons/falcon.js");
const { GuardianAngelCompanion: Angel } = await load("js/summons/angel.js");
const { autoSummonLoot, autoSummonDefence } = await load("js/summons/automation.js");
const stage = { id: "hub", bounds: { minX: 0, minY: 0, maxX: 400, maxY: 400 }, isInsideSafeZone: () => false };
const p = new Player(40, 40, { id: "knight" }); p.toggleAutoAttack();
const manager = { enemies: [], stage, damage(e) { e.hit = true; e.credit = this.hitSource; } };
const loot = new LootManager(); let questItem, source;
loot.onQuestItem = id => { questItem = id; }; loot.onCollect = i => { source = i.guildSource; };
const pet = p.familiar = new Familiar("slime", 40, 40);
loot.drop({ x: 155, y: 55 }, { id: "herb", qty: 2 }, false, stage); loot.items[0].guildSource = "herb";
for (let i = 0; i < 100 && loot.items.length; i++) pet.update(p, manager, null, loot, false, stage);
assert.equal(p.bag.count("herb"), 2); assert.equal(loot.items.length, 0); assert.equal(source, "herb"); assert.equal(p.x, 40);
loot.drop({ x: 100, y: 55 }, { id: "heartstone" }, true, stage);
for (let i = 0; i < 100 && loot.items.length; i++) pet.update(p, manager, null, loot, false, stage);
assert.equal(questItem, "heartstone"); assert.equal(p.bag.count("heartstone"), 1);
const threat = { x: pet.x, y: pet.y, isAlive: true, engaged: true };
manager.enemies = [threat]; pet.cd = 0; loot.drop({ x: 150, y: 80 }, { id: "salve" }, false, stage);
pet.update(p, manager, null, loot, false, stage);
assert.ok(threat.hit); assert.equal(threat.credit, "player"); assert.equal(pet.autoLootTarget, null);
manager.enemies = []; p.toggleAutoAttack(); assert.equal(autoSummonLoot(pet, p, manager, loot, null, stage), false);
p.toggleAutoAttack(); pet.aboard = true; assert.equal(autoSummonLoot(pet, p, manager, loot, null, stage), false); pet.aboard = false;
const full = new Player(0, 0, { id: "knight" }); full.toggleAutoAttack(); full.bag.slots = Array.from({ length: 40 }, () => ({ id: "broadsword@1", qty: 1 }));
const fullLoot = new LootManager(); fullLoot.drop({ x: 10, y: 20 }, { id: "herb" }, false, stage);
assert.equal(autoSummonLoot({ x: 0, y: 0 }, full, manager, fullLoot, null, stage), true); assert.equal(fullLoot.items.length, 1); assert.equal(full.bag.count("herb"), 0);
fullLoot.items.push({ x: 10, y: 20, type: "gold", amount: .0001 });
const goldBefore = full.gold; autoSummonLoot({ x: 0, y: 0 }, full, manager, fullLoot, null, stage); assert.equal(full.gold, goldBefore + .0001);
full.bag.slots[0] = { id: "herb", qty: full.bag.maxStack({ type: "consumable" }) - 1 };
const stackBefore = full.bag.count("herb"); const bundle = { type: "item", id: "herb", inst: { id: "herb", qty: 2 }, x: 10, y: 20 };
fullLoot.items.push(bundle); assert.equal(fullLoot.pickUp(full, bundle, null), false);
assert.equal(full.bag.count("herb"), stackBefore, "failed bundle pickup restores partially filled stacks");
const archer = new Player(40, 40, { id: "archer" }); archer.toggleAutoAttack(); archer.falconCompanion = new FalconCompanion(40, 40);
manager.enemies = [{ x: 80, y: 40, isAlive: true }]; autoSummonDefence(archer, manager, stage, Angel);
assert.equal(archer.falconCompanion.state, "ATTACKING"); assert.equal(archer.skillCooldownTimer, 220);
archer.skillCooldownTimer = 0; archer.falconCompanion.state = "HOVERING"; archer.errand = { runner: "falcon" };
autoSummonDefence(archer, manager, stage, Angel); assert.equal(archer.falconCompanion.state, "HOVERING");
manager.enemies = []; archer.errand = null;
const flyingLoot = new LootManager(); flyingLoot.drop({ x: 155, y: 55 }, { id: "salve" }, false, stage);
for (let i = 0; i < 100 && flyingLoot.items.length; i++) archer.falconCompanion.update(archer, manager, null, flyingLoot);
assert.equal(archer.bag.count("salve"), 1);
manager.enemies = [{ x: 80, y: 40, isAlive: true }];
const priest = new Player(40, 40, { id: "priest" }); priest.toggleAutoAttack();
autoSummonDefence(priest, manager, stage, Angel); assert.equal(priest.angelCompanions.length, 1);
autoSummonDefence(priest, manager, stage, Angel); assert.equal(priest.angelCompanions.length, 1);
priest.skillCooldownTimer = 0; autoSummonDefence(priest, manager, stage, Angel); assert.equal(priest.angelCompanions.length, 2);
priest.angelCompanions[0].isAlive = false; priest.skillCooldownTimer = 0; autoSummonDefence(priest, manager, stage, Angel); assert.equal(priest.angelCompanions.length, 2);
priest.autoAttack.until = Date.now() - 1; priest.angelCompanions = []; priest.skillCooldownTimer = 0;
autoSummonDefence(priest, manager, stage, Angel); assert.equal(priest.angelCompanions.length, 0);
priest.autoAttack.remainingMs = 60000; priest.toggleAutoAttack(); manager.enemies = [];
const angel = new Angel(40, 40, 100), angelLoot = new LootManager(); angelLoot.drop({ x: 155, y: 55 }, { id: "salve" }, false, stage);
for (let i = 0; i < 100 && angelLoot.items.length; i++) angel.update(priest, manager, null, angelLoot, 0, false);
assert.equal(priest.bag.count("salve"), 1); assert.ok(angel.lifespan < 720);
priest.angelCompanions = []; priest.skillCooldownTimer = 0;
angelLoot.drop({ x: 150, y: 55 }, { id: "salve" }, false, stage);
autoSummonDefence(priest, manager, stage, Angel, angelLoot); assert.equal(priest.angelCompanions.length, 1, "Z summons a guardian for nearby loot even without a foe");
console.log("Z summons: pet pickups/quest/source callbacks, defensive priority, disabled/expired/aboard guards, full bags, falcon strikes/errands and angel cooldown/replacement passed");
// A walking collector must physically travel through the opening in a wall.
const { footBlocked } = await load("js/world/nav.js");
const cols = 20, rows = 20, solid = new Uint8Array(cols * rows);
for (let y = 0; y < 15; y++) solid[y * cols + 9] = 1;
const maze = { id: "hub", width: 320, height: 320, tilemap: { cols, rows, solid, inBounds: (x,y) => x >= 0 && y >= 0 && x < cols && y < rows, idx: (x,y) => y*cols+x }, bounds: { minX: 0, minY: 0, maxX: 290, maxY: 290 } };
const owner = new Player(90, 44, { id: "knight" }); owner.toggleAutoAttack();
const walker = new Familiar("slime", 46, 44), wallLoot = new LootManager(); wallLoot.drop({ x: 248, y: 64 }, { id: "herb" }, false, maze);
const { AdventureNavigator } = await load("js/autoadventure.js");
walker.autoLootNavigator = new AdventureNavigator();
const build = walker.autoLootNavigator.build.bind(walker.autoLootNavigator); let simulatedTime = 0;
walker.autoLootNavigator.build = (stage, actor) => build(stage, actor, simulatedTime);
let opening = false;
for (let frame = 0; frame < 1500 && wallLoot.items.length; frame++) {
  simulatedTime = frame * 17;
  autoSummonLoot(walker, owner, { enemies: [] }, wallLoot, null, maze, { x: 8, y: 15, speed: 2.5 });
  assert.equal(footBlocked(maze, walker.x + 8, walker.y + 15), false);
  if (walker.y + 15 > 240) opening = true;
}
assert.ok(opening, `collector ended at ${walker.x},${walker.y}; remaining ${wallLoot.items.length}`); assert.equal(owner.bag.count("herb"), 1);
console.log("Walking pet loot route navigated around real tile obstacles");
