import assert from 'node:assert/strict';
import {load} from './headless.mjs';
const {Workshop,craftingStation}=await load('js/workshop.js');
const {Player}=await load('js/player.js');
const {recipeFor}=await load('js/items/craftsets.js');
const {craftPiece}=await load('js/items/crafting.js');
const p=new Player(100,100,{id:'knight'});p.level=25;
for(const id of ['hub','ash','siege'])assert.ok(craftingStation({id,isInsideSafeZone:()=>true},p));
assert.equal(craftingStation({id:'canopy',isInsideSafeZone:()=>true},p),false);
assert.equal(craftingStation({id:'hub',isInsideSafeZone:()=>false},p),false);
let allowed=false,options;const w=new Workshop({canCraft:()=>allowed,menu:{show:(title,rows)=>options=rows}});
w.open(p);assert.equal(options[0].disabled,true);assert.equal(options[1].disabled,true);
const recipe=recipeFor('str10','weapon');p.gold=recipe.gold+100;for(const [id,n] of Object.entries(recipe))if(id!=='gold')p.bag.add(id,n);
p.craft={auto:true,target:'str10'};const before=p.bag.slots.length;
for(let i=0;i<100;i++)w.update(p,true);assert.equal(p.bag.slots.length,before);assert.equal(p.gold,recipe.gold+100);
assert.equal(craftPiece(p,'str10','weapon'),'');assert.equal(p.gold,100);for(const [id] of Object.entries(recipe))if(id!=='gold')assert.equal(p.bag.count(id),0);
assert.equal(craftPiece(p,'str10','weapon'),'materials');
allowed=true;w.open(p);assert.equal(options[0].disabled,false);
console.log('PASS: designated safe-zone forges, blocked field/other camps, disabled crafting and auto-crafting, exact ore/fee consumption');
