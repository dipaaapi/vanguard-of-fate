import assert from "node:assert/strict";
import { load } from "./headless.mjs";
const { Player } = await load("js/player.js");
const { coinBreakdown, formatCoins, buyPrice } = await load("js/items/economy.js");
const { getItem } = await load("js/items/itemdb.js");
let now = 1000000;
const realNow = Date.now;
Date.now = () => now;
try {
  let attacks = 0;
  const p = new Player(0, 0, { id: "novice", range: 60, onAttack: () => { attacks++; } });
  assert.equal(p.autoAttackTime(), 300000);
  assert.equal(p.toggleAutoAttack(), true);
  now += 60000;
  assert.equal(p.autoAttackTime(), 240000);
  p.update({}, null, () => {}, { x: 15, y: 0, isAlive: true });
  assert.equal(attacks, 1);
  p.attackCooldownTimer = 0;
  p.update({}, null, () => {}, { x: 15, y: 0, isAlive: true }, true);
  assert.equal(attacks, 1);
  p.update({}, null, () => {}, { x: 1000, y: 0, isAlive: true });
  assert.equal(attacks, 1);
  assert.equal(p.toggleAutoAttack(), false);
  now += 900000;
  assert.equal(p.autoAttackTime(), 240000);
  p.toggleAutoAttack();
  const saved = JSON.parse(JSON.stringify(p.autoAttack));
  now += 240001;
  const loaded = new Player(0, 0, { id: "novice" });
  loaded.autoAttack = saved;
  assert.equal(loaded.autoAttackTime(), 0);
  assert.equal(loaded.toggleAutoAttack(), false);
  assert.equal(loaded.autoAttack.until, 0);
  assert.equal(buyPrice("safezone", "soulstone", getItem("soulstone")), 10000);
  assert.equal(loaded.bag.add("soulstone", 1), true);
  assert.ok(loaded.bag.useById("soulstone", loaded));
  assert.equal(loaded.bag.count("soulstone"), 0);
  assert.equal(loaded.autoAttackTime(), 600000);
  loaded.toggleAutoAttack();
  now += 1000;
  loaded.extendAutoAttack(600000);
  assert.equal(loaded.autoAttackTime(), 1199000);
  assert.deepEqual(coinBreakdown(101.0101), { platinum: 1, gold: 1, silver: 1, bronze: 1 });
  assert.equal(formatCoins(10000), "100P");
  assert.equal(formatCoins(0), "0B");
  assert.equal(formatCoins(0.01), "1S");
  assert.equal(formatCoins(0.0001), "1B");
  const refill = new Player(0,0,{id:"novice"});
  refill.autoAttack={remainingMs:0,until:0};refill.bag.add("soulstone",3);
  assert.equal(refill.toggleAutoAttack(),true);assert.equal(refill.bag.count("soulstone"),2);
  assert.equal(refill.autoAttackTime(),600000);
  now+=589999;assert.equal(refill.refillAutoAttack(),false);
  now+=1;assert.equal(refill.refillAutoAttack(),true);
  assert.equal(refill.autoAttackTime(),610000);assert.equal(refill.bag.count("soulstone"),1);
  assert.equal(refill.refillAutoAttack(),false,"one stone per threshold crossing");
  assert.equal(refill.toggleAutoAttack(),false);assert.equal(refill.bag.count("soulstone"),1,"turning off never consumes");
  assert.equal(refill.refillAutoAttack(),false,"disabled auto never refills");
  assert.equal(refill.toggleAutoAttack(),true);assert.equal(refill.bag.count("soulstone"),0,"Z consumes a stone on activation");
  now=refill.autoAttack.until+1;assert.equal(refill.refillAutoAttack(),false);assert.equal(refill.autoAttackTime(),0);
  assert.equal(refill.toggleAutoAttack(),false,"no stones and no time cannot start");
  console.log("Auto-attack timer, targeting, offline expiry, soulstones, and coin conversions passed.");
} finally { Date.now = realNow; }
