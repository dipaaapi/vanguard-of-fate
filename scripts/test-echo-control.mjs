import assert from 'node:assert/strict';
import {load} from './headless.mjs';
const {Player}=await load('js/player.js');
const {Party}=await load('js/party.js');
const {buyPremium,demoTopUp,retainPremiumForRegression}=await load('js/premium.js');
const {Keybinds}=await load('js/keybinds.js');
const p=new Player(0,0,{id:'priest'}),party=new Party();demoTopUp(p,3000);
assert.ok(buyPremium(p,party,'summon:vaelThorn').ok);
assert.deepEqual(party.members,['hero','vaelThorn']);assert.equal(party.recruited('vaelThorn'),false);
assert.equal(Keybinds.label('party2'),'Alt+2');
assert.ok(Keybinds.matches('party2',{code:'Digit2',altKey:true}));
for(const e of [{code:'Digit2'},{code:'Digit2',shiftKey:true},{code:'Digit2',altKey:true,ctrlKey:true}])assert.equal(Keybinds.matches('party2',e),false);
assert.equal(party.switchTo(1,p,true),'vaelThorn');assert.equal(p.active.id,'vaelThorn');
p.hp=37;const saved=party.serialize(p),restored=new Party(saved,party.book.serialize(),p.premium.summons);restored.apply(p);
assert.equal(restored.activeId,'vaelThorn');assert.equal(p.hp,37);
assert.deepEqual(new Party(saved,party.book.serialize()).members,['hero'],'unowned Echo cannot be restored');
assert.ok(buyPremium(p,restored,'recruit:vaelThorn').ok);assert.equal(restored.members.filter(id=>id==='vaelThorn').length,1);assert.equal(p.hp,37);
const echoOwner=new Player(0,0,{id:'knight'}),echoParty=new Party();demoTopUp(echoOwner,500);buyPremium(echoOwner,echoParty,'summon:vaelThorn');
const next=new Player(0,0,{id:'knight'}),nextParty=new Party();retainPremiumForRegression(echoOwner,next,nextParty);
assert.ok(nextParty.members.includes('vaelThorn'));assert.equal(nextParty.recruited('vaelThorn'),false);assert.equal(nextParty.switchTo(1,next,true),'vaelThorn');
next.hp=0;nextParty.rescue(next);assert.equal(nextParty.switchTo(1,next,true),null);
console.log('PASS: Alt selection, Echo-only ownership, save/load, duplicate-free recruitment, Regression retention and fallen-member protection');
