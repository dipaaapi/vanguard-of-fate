// ==================== 2. FIGHTER CLASS DATA & LOGIC ====================
export const FighterClass = {
    id: "fighter",
    name: "Fighter",
    title: "Brawler",
    speed: 1.55,
    attackCooldown: 50, // 0.83 second bago makapaghagis muli ng Force Sphere
    cooldown: 180,       // 3 seconds para sa Flying Kick
    sprites: {
        idle: fighterIdle,
        run: fighterIdle,
        slash: fighterPunch,
        bash: fighterKick
    },

    onAttack(player, target, spawnProjectile) {
        const spawnX = player.x + 12;
        const spawnY = player.y + 12;
        const cos = Math.cos(player.aimAngle);
        const sin = Math.sin(player.aimAngle);

        spawnProjectile({
            type: "force_sphere",
            x: spawnX,
            y: spawnY,
            vx: cos * 4.0,
            vy: sin * 4.0,
            angle: player.aimAngle
        });
    },

    onSkill(player, target) {
        if (target && target.isAlive && target.isMarkedCritical) {
            player.isHomingKick = true;
        } else {
            player.isHomingKick = false;
        }
    },

    onSkillUpdate(player, target, onImpact) {
        if (player.isHomingKick && target && target.isAlive) {
            const sideOffset = player.x < target.x ? -14 : 14;
            const destX = target.x + sideOffset;
            const destY = target.y;

            const dx = destX - player.x;
            const dy = destY - player.y;
            const dist = Math.hypot(dx, dy);

            if (dist > 14) {
                player.x += (dx / dist) * 8.0;
                player.y += (dy / dist) * 8.0;
                player.facing = dx >= 0 ? "right" : "left";
            } else {
                // Garantisadong impact
                player.x = destX;
                player.y = destY;
                player.isHomingKick = false;
                player.state = "idle";

                if (onImpact) {
                    onImpact(50, true);
                }
            }
        } else if (player.animFrame === 1 && !player.isHomingKick) {
            player.x += Math.cos(player.aimAngle) * 3.5;
            player.y += Math.sin(player.aimAngle) * 3.5;
        }
    }
};